execFileSync('ffmpeg',['-y','-i',source,'-filter_complex','fps=16,scale=960:-1:flags=lanczos,split[s0][s1];[s0]palettegen=max_colors=128[p];[s1][p]paletteuse=dither=bayer:bayer_scale=3','-loop','0',resolve(output,'06-motion.gif')],{stdio:'ignore'});
console.log('Saved speaking screenshot, MP4 and GIF to Design/Previews.');
